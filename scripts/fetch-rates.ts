/**
 * Build step: bakes the latest official NBG rate into src/data/fallbackRates.ts,
 * so the converter works offline even on a phone that never loaded a rate.
 *
 *   node scripts/fetch-rates.ts
 *
 * Never fails the build: on any error it keeps the existing file.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { parseNbgResponse } from '../src/lib/currency/rates.ts';

const NBG_URL = 'https://nbg.gov.ge/gw/api/ct/monetarypolicy/currencies/en/json/';
const TIMEOUT_MS = 15_000;
const OUT = fileURLToPath(new URL('../src/data/fallbackRates.ts', import.meta.url));

try {
  const res = await fetch(NBG_URL, {
    headers: {
      Accept: 'application/json',
      'User-Agent': 'gudauri-2027 build (github.com/Ofekfa/gudauri-2027)',
    },
    signal: AbortSignal.timeout(TIMEOUT_MS),
  });
  if (!res.ok) throw new Error(`NBG responded ${res.status}`);
  const rates = parseNbgResponse(await res.json());
  const source = `/**
 * Generated by scripts/fetch-rates.ts at build time. Do not edit by hand.
 * Last official NBG rate, used only when the app has no saved rate and no connection.
 */
import type { Rates } from '../lib/currency/rates';

export const FALLBACK_RATES: Rates = {
  gelPer: { ILS: ${rates.gelPer.ILS}, EUR: ${rates.gelPer.EUR} },
  validFrom: '${rates.validFrom}',
  source: '${rates.source}',
};

/** When this file was generated (ISO). */
export const FALLBACK_RATES_GENERATED_AT = '${new Date().toISOString()}';
`;
  await writeFile(OUT, source);
  console.log(`Fallback rate updated: 1 ILS = ${rates.gelPer.ILS} GEL (valid ${rates.validFrom}).`);
} catch (err) {
  console.warn(`Fallback rate not updated (keeping the existing file): ${String(err)}`);
}
